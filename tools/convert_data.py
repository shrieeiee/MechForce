"""Convert the original MechForce (Amiga, 1989, Ralph H. Reed) disk data into JS modules.

Usage:  python3 tools/extract_adf.py MechForce.adf disk/
        python3 tools/convert_data.py disk/ src/core/mechdata.js src/client/samples.js

Mech file layout (904 bytes, big-endian 16-bit words):
  0   name (14 bytes)
  14  armour, 11 zones: H, LT, CT, RT, LT(rear), CT(rear), RT(rear), LA, RA, LL, RL
  36  max armour (same 11)
  58  critical table: 8 locations (H, LT, CT, RT, LA, RA, LL, RL) x 12 slots
  250 max critical table (copy)
  442 internal structure, 8 locations
  458 weapon records, 34 bytes each: flag, FFP ammo tons, FFP weapon tons,
      type, heat, damage, range, min range, slots, ammo, max ammo, loc, slot, ammo loc, ammo slot
  864 heat sinks, max heat sinks, tonnage ...
"""
import sys, os, struct, json, base64, io, wave

root, out_js, out_snd = sys.argv[1], sys.argv[2], sys.argv[3]

def w(b, o):
    v = struct.unpack('>H', b[o:o + 2])[0]
    return -1 if v == 0xFFFF else v

# Known classic speeds (walk MP). Others derive from tonnage.
SPEED = {
    'Locust': 8, 'Locust_3V': 8, 'Spider': 8, 'Jenner': 7, 'Commando': 6, 'Wasp': 6, 'Super_Wasp': 6, 'Stinger': 6,
    'Hornet': 5, 'Valkyrie': 5, 'Panther': 4, 'Firestarter': 6, 'Whitworth': 4, 'Javelin': 6, 'Wolfhound': 7,
    'Falcon': 6, 'Raven': 6, 'Assassin': 7, 'Hermes II': 6, 'Clint': 6, 'Hunchback': 4, 'Dragon': 5, 'Griffin': 5,
    'Phoenix_Hawk': 6, 'Shadow_Hawk': 5, 'Shadow_HawkD': 5, 'Wolverine': 5, 'Wolverine_M': 5, 'Centurion': 4,
    'Trebuchet': 5, 'Blackjack': 4, 'Enforcer': 4, 'Enforcer-4R': 4, 'Hatchetman': 4, 'Vindicator': 4,
    'Dervish': 5, 'Chameleon': 6, 'Archer': 4, 'Catapult': 4, 'Crusader': 4, 'Marauder': 4, 'Rifleman': 4,
    'Rifleman_V': 4, 'Warhammer': 4, 'Warhammer_6L': 4, 'Warhammer-6K': 4, 'Quickdraw': 5, 'Thunder_Bolt': 4,
    'Orion': 4, 'Grasshopper': 4, 'JagerMech': 4, 'Cataphract': 4, 'Ostsol': 5, 'Zeus': 4, 'Goliath': 4,
    'Awesome': 3, 'Awesome-8R': 3, 'Atlas': 3, 'AtlasII': 3, 'Banshee': 3, 'Battlemaster': 4, 'Stalker': 3,
    'Cyclops': 4, 'Victor': 4,
}

CLASSES = ['Light', 'Medium', 'Heavy', 'Assault']
mechs = []
for ci, cls in enumerate(CLASSES):
    d = os.path.join(root, 'mechs', cls)
    for fn in sorted(os.listdir(d), key=lambda s: s.lower()):
        b = open(os.path.join(d, fn), 'rb').read()
        name = b[:14].split(b'\0')[0].decode('latin1')
        tons = int(fn.rsplit('.', 1)[1])
        armor = [max(0, w(b, 14 + 2 * i)) for i in range(11)]
        crit = [[w(b, 58 + 24 * k + 2 * s) for s in range(12)] for k in range(8)]
        internal = [max(1, w(b, 442 + 2 * i)) for i in range(8)]
        weps = []
        o = 458
        for _ in range(11):
            ws = [w(b, o + 10 + 2 * i) for i in range(12)]
            if 0 <= ws[8] < 8 and 0 <= ws[0] <= 16 and (ws[2] > 0):
                # type, heat, dmg, range, minr, slots, ammo, loc, slot, aloc, aslot
                weps.append([ws[0], max(0, ws[1]), ws[2], max(1, ws[3]), max(0, ws[4]), max(1, ws[5]), max(0, ws[6]),
                             ws[8], ws[9], ws[10], ws[11]])
            o += 34
        flat = sum(crit, [])
        jets = flat.count(50) + flat.count(52)
        hs = w(b, 864)
        walk = SPEED.get(name)
        if walk is None:
            walk = 7 if tons <= 20 else 6 if tons <= 35 else 5 if tons <= 55 else 4 if tons <= 75 else 3 if tons <= 100 else 2
        jump = min(jets, walk) if jets else 0
        mechs.append(dict(n=name.replace('_', ' '), c=ci, t=tons, a=armor, i=internal, hs=max(hs, 1), w=walk, j=jump,
                          wp=weps, cr=crit))

with open(out_js, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/convert_data.py from the original MechForce v3.79 disk (Ralph H. Reed, 1987-89).\n')
    f.write('export const MECHS = ' + json.dumps(mechs, separators=(',', ':'), ensure_ascii=False) + ';\n')
print('mechs', len(mechs))

# Orders (mission briefings): two Pascal-ish strings after a small header; pull the two long text runs.
orders = {}
od = os.path.join(root, 'Orders')
for fn in sorted(os.listdir(od)):
    b = open(os.path.join(od, fn), 'rb').read()
    runs, cur = [], bytearray()
    for ch in b:
        if ch == 0 and cur:
            ch = 32  # \0 marks a line wrap in the original text
        if 32 <= ch < 127:
            cur.append(ch)
        else:
            if len(cur) > 60: runs.append(cur.decode('latin1').strip())
            cur = bytearray()
    if len(cur) > 60: runs.append(cur.decode('latin1').strip())
    orders[fn] = runs
json.dump(orders, open(os.path.join(os.path.dirname(out_js), 'orders.json'), 'w'), indent=1)

# Sounds: raw signed 8-bit mono PCM. Wrap as WAV (unsigned 8-bit) base64.
RATE = 10000
snds = {}
for fn in sorted(os.listdir(os.path.join(root, 'Snd'))):
    raw = open(os.path.join(root, 'Snd', fn), 'rb').read()
    u8 = bytes(((x + 128) & 0xFF) for x in raw)
    bio = io.BytesIO()
    wv = wave.open(bio, 'wb'); wv.setnchannels(1); wv.setsampwidth(1); wv.setframerate(RATE); wv.writeframes(u8); wv.close()
    snds[fn.split('.')[0]] = base64.b64encode(bio.getvalue()).decode()
with open(out_snd, 'w') as f:
    f.write('// Original MechForce digitised sounds (8-bit, ~10kHz), wrapped as WAV.\n')
    f.write('export const AMIGA_SAMPLES = ' + json.dumps(snds) + ';\n')
print('sounds', list(snds))
