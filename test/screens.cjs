const { chromium } = require('playwright');
const OUT = process.env.OUT;
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await b.newContext({ viewport: { width: 1280, height: 800 } });
  await ctx.addInitScript(() => localStorage.setItem('mechforce.settings', JSON.stringify({ quality: 'medium', speed: 2 })));
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('file://' + process.cwd() + '/dist/web/index.html');
  await p.waitForTimeout(9000);
  await p.screenshot({ path: OUT + '/20-title.png' });
  await p.keyboard.press('ArrowDown'); await p.keyboard.press('ArrowDown'); await p.keyboard.press('ArrowDown'); await p.keyboard.press('Enter');
  await p.waitForTimeout(1500);
  await p.keyboard.press('Tab'); await p.keyboard.press('Tab'); await p.keyboard.press('ArrowDown'); await p.keyboard.press('ArrowDown');
  await p.waitForTimeout(800);
  await p.screenshot({ path: OUT + '/21-bay.png' });
  const m = await b.newContext({ viewport: { width: 844, height: 390 }, isMobile: true, hasTouch: true });
  await m.addInitScript(() => localStorage.setItem('mechforce.settings', JSON.stringify({ quality: 'low', speed: 8 })));
  const q = await m.newPage(); q.on('pageerror', (e) => errs.push('m:' + e.message));
  await q.goto('file://' + process.cwd() + '/dist/web/index.html');
  await q.waitForTimeout(3000);
  await q.tap('[data-key=skirmish]');
  await q.waitForTimeout(1500);
  await q.screenshot({ path: OUT + '/22-phone-lobby.png' });
  await q.tap('[data-key=start]');
  await q.waitForTimeout(2500);
  await q.tap('[data-k=go]');
  await q.waitForTimeout(3000);
  await q.screenshot({ path: OUT + '/23-phone-battle.png' });
  console.log('errors', errs);
  await b.close();
})();
